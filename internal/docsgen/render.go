package docsgen

import (
	"bytes"
	"fmt"
	"strings"
)

// renderMarkdown writes p as a page of the documentation site.
func renderMarkdown(p *manPage) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "---\ntitle: %s\nweight: %d\n---\n\n", p.title, p.weight)
	b.WriteString("<!-- Generated by `mise run docs:reference` from the CLI's help texts. Do not edit. -->\n\n")
	fmt.Fprintf(&b, "# %s\n", p.title)
	for _, s := range p.sections {
		fmt.Fprintf(&b, "\n## %s\n", s.title)
		for _, bl := range s.blocks {
			b.WriteString("\n")
			writeMarkdownBlock(&b, bl)
		}
	}
	return b.Bytes()
}

func writeMarkdownBlock(b *bytes.Buffer, bl block) {
	switch bl.kind {
	case blockPara:
		b.WriteString(mdEscape(bl.text) + "\n")
	case blockPre, blockSynopsis:
		lang := "text"
		if strings.HasPrefix(bl.text, "$ ") {
			lang = "console"
		}
		fmt.Fprintf(b, "```%s\n%s\n```\n", lang, bl.text)
	case blockSub:
		fmt.Fprintf(b, "### %s\n", bl.text)
	case blockDefs:
		for i, d := range bl.defs {
			if i > 0 {
				b.WriteString("\n")
			}
			b.WriteString(mdSpans(d.term) + "\n")
			for j, p := range d.body {
				if j == 0 {
					b.WriteString(":   " + mdEscape(indentCont(p)) + "\n")
				} else {
					b.WriteString("\n    " + mdEscape(indentCont(p)) + "\n")
				}
			}
			if d.meta != "" {
				if len(d.body) == 0 {
					b.WriteString(":   *" + d.meta + "*\n")
				} else {
					b.WriteString("\n    *" + d.meta + "*\n")
				}
			}
		}
	case blockLinks:
		for _, l := range bl.links {
			if l.man != "" {
				fmt.Fprintf(b, "- [`%s`](%s)\n", l.text, l.href)
			} else {
				fmt.Fprintf(b, "- [%s](%s)\n", l.text, l.href)
			}
		}
	}
}

// indentCont indents the continuation lines of a definition paragraph.
func indentCont(s string) string { return strings.ReplaceAll(s, "\n", "\n    ") }

func mdSpans(spans []span) string {
	var b strings.Builder
	for _, s := range spans {
		switch {
		case s.href != "":
			fmt.Fprintf(&b, "[`%s`](%s)", s.text, s.href)
		case s.style == styleCode:
			fmt.Fprintf(&b, "`%s`", s.text)
		case s.style == styleVar:
			fmt.Fprintf(&b, "*%s*", s.text)
		default:
			b.WriteString(mdEscape(s.text))
		}
	}
	return b.String()
}

// mdEscape keeps plain help text from being read as HTML or emphasis.
func mdEscape(s string) string {
	return strings.NewReplacer("<", "&lt;", "*", `\*`).Replace(s)
}

// renderRoff writes p as a man(7) page. There is no date in .TH, so the
// page only changes when the commands do.
func renderRoff(p *manPage) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, ".TH %q \"1\" \"\" \"odoo-work-cli\" \"odoo-work-cli manual\"\n", strings.ToUpper(p.name))
	b.WriteString(".\\\" Generated by `mise run docs:reference` from the CLI's help texts. Do not edit.\n")
	for _, s := range p.sections {
		fmt.Fprintf(&b, ".SH %s\n", s.title)
		first := true
		for _, bl := range s.blocks {
			writeRoffBlock(&b, bl, first)
			first = false
		}
	}
	return b.Bytes()
}

func writeRoffBlock(b *bytes.Buffer, bl block, first bool) {
	switch bl.kind {
	case blockPara:
		if !first {
			b.WriteString(".PP\n")
		}
		b.WriteString(roffText(bl.text) + "\n")
	case blockPre:
		b.WriteString(".PP\n.RS 4\n.nf\n" + roffText(bl.text) + "\n.fi\n.RE\n")
	case blockSynopsis:
		// One .SY per form: the command path in bold, the arguments filled
		// with a hanging indent; a bracketed group never breaks.
		for _, l := range strings.Split(bl.text, "\n") {
			head, rest := splitSynopsis(l)
			b.WriteString(".SY \"" + roffText(head) + "\"\n")
			if rest != "" {
				b.WriteString(roffKeepGroups(rest) + "\n")
			}
			b.WriteString(".YS\n")
		}
	case blockSub:
		fmt.Fprintf(b, ".SS %s\n", roffText(bl.text))
	case blockDefs:
		for _, d := range bl.defs {
			b.WriteString(".TP\n" + roffSpans(d.term) + "\n")
			for i, p := range d.body {
				if i > 0 {
					b.WriteString(".IP\n")
				}
				b.WriteString(roffText(p) + "\n")
			}
			if d.meta != "" {
				if len(d.body) > 0 {
					b.WriteString(".br\n")
				}
				b.WriteString(`\fI` + roffText(d.meta) + `\fR` + "\n")
			}
		}
	case blockLinks:
		var cmds []string
		var pages []link
		for _, l := range bl.links {
			if l.man != "" {
				cmds = append(cmds, `\fB`+roffText(l.man)+`\fR(1)`)
			} else {
				pages = append(pages, l)
			}
		}
		if len(cmds) > 0 {
			if !first {
				b.WriteString(".PP\n")
			}
			b.WriteString(strings.Join(cmds, ",\n") + "\n")
		}
		for _, l := range pages {
			b.WriteString(".PP\n" + roffText(l.text) + ":\n.UR " + l.url + "\n.UE\n")
		}
	}
}

// splitSynopsis splits a synopsis form into the command path (the
// leading lower-case words) and its arguments.
func splitSynopsis(l string) (string, string) {
	words := strings.Fields(l)
	n := 0
	for n < len(words) && !strings.ContainsAny(words[n][:1], "-[<|") && strings.ToLower(words[n]) == words[n] &&
		!strings.Contains(words[n], "|") {
		n++
	}
	return strings.Join(words[:n], " "), strings.Join(words[n:], " ")
}

// roffKeepGroups escapes synopsis arguments and makes the blanks inside
// [ ] unbreakable.
func roffKeepGroups(s string) string {
	var b strings.Builder
	depth := 0
	for _, r := range s {
		switch r {
		case '[':
			depth++
		case ']':
			depth--
		}
		if r == ' ' && depth > 0 {
			b.WriteString(`\ `)
			continue
		}
		b.WriteRune(r)
	}
	return strings.ReplaceAll(roffText(b.String()), `\e `, `\ `)
}

func roffSpans(spans []span) string {
	var b strings.Builder
	for _, s := range spans {
		switch {
		case s.man != "":
			fmt.Fprintf(&b, `\fB%s\fR(1)`, roffText(s.man))
		case s.style == styleCode:
			fmt.Fprintf(&b, `\fB%s\fR`, roffText(s.text))
		case s.style == styleVar:
			fmt.Fprintf(&b, `\fI%s\fR`, roffText(s.text))
		default:
			b.WriteString(roffText(s.text))
		}
	}
	return b.String()
}

// roffText escapes plain text for roff: backslashes, hyphens (so options
// stay copy-pasteable ASCII) and a dot or quote at the start of a line,
// which would otherwise be read as a request.
func roffText(s string) string {
	s = strings.NewReplacer(`\`, `\e`, "-", `\-`).Replace(s)
	lines := strings.Split(s, "\n")
	for i, l := range lines {
		if strings.HasPrefix(l, ".") || strings.HasPrefix(l, "'") {
			lines[i] = `\&` + l
		}
	}
	return strings.Join(lines, "\n")
}
